#!/usr/bin/env node
/**
 * summarize-results.js — aggregate k6 run summaries into history.json
 *
 * Reads every latest-*.json file written by k6 handleSummary hooks and
 * appends new entries to results/history.json (max 500 entries, oldest
 * pruned first).  Also regenerates dashboards/data.js so the results
 * dashboard can be opened as a local file without CORS issues.
 *
 * Called automatically by run-load-tests.sh after each k6 run.
 * Can also be run manually:
 *
 *   node test/LoadTests/scripts/summarize-results.js
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const LOAD_TESTS_DIR  = path.join(__dirname, '..');
const RESULTS_DIR     = path.join(LOAD_TESTS_DIR, 'results');
const HISTORY_FILE    = path.join(RESULTS_DIR, 'history.json');
const DASHBOARD_DATA  = path.join(LOAD_TESTS_DIR, 'dashboards', 'data.js');
const MAX_HISTORY     = 500;

// ── Read existing history ─────────────────────────────────────────────────
let history = [];
if (fs.existsSync(HISTORY_FILE)) {
  try {
    history = JSON.parse(fs.readFileSync(HISTORY_FILE, 'utf8'));
    if (!Array.isArray(history)) history = [];
  } catch {
    console.warn('history.json could not be parsed — starting fresh');
    history = [];
  }
}

// ── Collect latest-*.json summaries ──────────────────────────────────────
const latestFiles = fs.readdirSync(RESULTS_DIR)
  .filter((f) => f.startsWith('latest-') && f.endsWith('.json'))
  .map((f) => path.join(RESULTS_DIR, f));

let added = 0;
for (const file of latestFiles) {
  try {
    const raw     = fs.readFileSync(file, 'utf8');
    const summary = JSON.parse(raw);

    if (!summary.timestamp || !summary.scenario) {
      console.warn(`Skipping ${path.basename(file)}: missing timestamp or scenario`);
      continue;
    }

    // Deduplicate: skip if this exact timestamp+scenario already exists.
    const isDuplicate = history.some(
      (h) => h.timestamp === summary.timestamp && h.scenario === summary.scenario
    );

    if (!isDuplicate) {
      history.push(summary);
      added++;
      console.log(
        `  + ${summary.scenario} @ ${summary.timestamp} — ` +
        `passed: ${summary.passed}, ` +
        `p99: ${summary.metrics?.p99?.toFixed(1) ?? 'n/a'} ms`
      );
    }
  } catch (err) {
    console.warn(`Could not parse ${path.basename(file)}: ${err.message}`);
  }
}

// ── Sort by timestamp, prune oldest ──────────────────────────────────────
history.sort((a, b) => a.timestamp.localeCompare(b.timestamp));
if (history.length > MAX_HISTORY) {
  history = history.slice(-MAX_HISTORY);
}

// ── Write history.json ────────────────────────────────────────────────────
fs.mkdirSync(RESULTS_DIR, { recursive: true });
fs.writeFileSync(HISTORY_FILE, JSON.stringify(history, null, 2));
console.log(`\n  history.json: ${history.length} entries (${added} new)`);

// ── Regenerate dashboards/data.js ─────────────────────────────────────────
// Embedding as a JS variable lets the dashboard work as a local file (no
// CORS restriction that would block fetch() on file:// URLs).
const dataJs = `// Auto-generated by summarize-results.js — do not edit manually.
// Regenerated every time a load test run completes.
window.PERF_HISTORY = ${JSON.stringify(history, null, 2)};
`;
fs.mkdirSync(path.dirname(DASHBOARD_DATA), { recursive: true });
fs.writeFileSync(DASHBOARD_DATA, dataJs);
console.log(`  dashboards/data.js: updated (${history.length} entries)`);
